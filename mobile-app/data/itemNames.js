// (github.com/Ryan-J-D/Rust-Item-IDs): у части старых гайдов ID
// отличаются — не копируйте их вслепую. Неизвестное показывается
// как #itemId; полный словарь с категориями живёт в lootCats.js
// и тоже подхватывается здесь. Легко дополнить по rustlabs.com.
import { LOOT_ITEMS } from './lootCats';

export const ITEM_NAMES = {
  '-932201673': 'Скрап',
  '-151838493': 'Дерево',
  '-2099697608': 'Камень',
  '69511070': 'Металлические фрагменты',
  // Новые предметы из обновления (ТЗ 5.1): Kevlar (кевларовая броня), MK-A винтовка
  // ID уточняются по дампу v2252+; пока заглушка для будущего справочника
  'kevlar_armor': 'Kevlar (кевларовая броня)',
  'mk_a_rifle': 'MK-A (новая винтовка)',
  '-4031221': 'Металлическая руда',
  '-1157596551': 'Серная руда',
  '-1581843485': 'Сера',
  '-1982036270': 'МВК руда',
  '-1938052175': 'Уголь',
  '-946369541': 'Низкосортное топливо',
  '-265876753': 'Порох',
  '-858312878': 'Ткань',
};

export function itemName(itemId, lang = 'ru') {
  const id = String(itemId);
  const hit = ITEM_NAMES[id];
  if (hit) return hit;
  const info = LOOT_ITEMS[id];
  if (info) return lang === 'ru' ? info.ru : info.en;
  return lang === 'ru' ? `Предмет #${itemId}` : `Item #${itemId}`;
}
